export function getOpening(id) {
  return OPENINGS.find((o) => o.id === id);
}

/** Normalisiert eine Variante: [{san, note}] und füllt fehlende Notizen über den Zugpfad. */
export function normalizeOpening(op) {
  const notesByPath = new Map();
  for (const line of op.lines) {
    const path = [];
    for (const m of line.moves) {
      const [san, note] = Array.isArray(m) ? m : [m, ""];
      path.push(san);
      const key = path.join(" ");
      if (note && !notesByPath.has(key)) notesByPath.set(key, note);
    }
  }
  return {
    ...op,
    lines: op.lines.map((line) => {
      const path = [];
      return {
        ...line,
        moves: line.moves.map((m) => {
          const [san, note] = Array.isArray(m) ? m : [m, ""];
          path.push(san);
          return { san, note: note || notesByPath.get(path.join(" ")) || "" };
        }),
      };
    }),
  };
}
